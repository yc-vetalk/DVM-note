for name, items in GROUPS:
    text += f"## {name}（{len(items)} 題）\n\n"
    for sub, key in items: text += block(sub, key) + "\n---\n\n"; n += 1
os.makedirs(os.path.dirname(paths.course_md('水產動物疾病學_自測題')), exist_ok=True)
open(paths.course_md('水產動物疾病學_自測題'), 'w', encoding='utf-8').write(text); print('題數', n)
