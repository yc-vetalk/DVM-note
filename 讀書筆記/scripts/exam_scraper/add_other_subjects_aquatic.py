def stem_opts(sub, key, n):
    t = open(f'{BASE}{sub}/試卷/{key}.md', encoding='utf-8').read()
    b = [x for x in re.split(r'\n### ', t)[1:] if x.split('.')[0] == str(n)][0].split('\n', 1)[1]
    stem = re.split(r'\n\n- A\.', b.strip())[0].strip()
    opts = re.findall(r'- ([A-D])\. (.*)', b)
    ans = re.search(r'官方答案：([^*]*)\*\*', b).group(1)
    return re.sub(r'\s+', ' ', stem), [o for _, o in opts], ans
